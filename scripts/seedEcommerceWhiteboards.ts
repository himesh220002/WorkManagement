async function seed() {
  await connectToDatabase();
  console.log("Connected to MongoDB for TaskPMS Enhanced E-commerce Whiteboard Plan generation...");

  let inserted = 0;
  let updated = 0;

  for (const b of BOARDS) {
    const existing = await Whiteboard.findOne({
      companyId: COMPANY_ID,
      title: b.title,
    });

    if (existing) {
      existing.description = b.description;
      existing.templateId = b.templateId;
      existing.isFavorite = b.isFavorite;
      existing.authorName = AUTHOR_NAME;
      existing.authorId = AUTHOR_ID;
      existing.authorInitials = AUTHOR_INITIALS;
      existing.nodes = b.nodes;
      existing.edges = b.edges;
      existing.updatedAt = new Date();
      await existing.save();
      await syncTenantWrite("Whiteboard", "update", existing, undefined, COMPANY_CODE);
      updated++;
      console.log(`Updated whiteboard: ${b.title} (${existing._id}) [Nodes: ${b.nodes.length}, Edges: ${b.edges.length}]`);
    } else {
      const created = await Whiteboard.create({
        companyId: COMPANY_ID,
        title: b.title,
        description: b.description,
        templateId: b.templateId,
        isFavorite: b.isFavorite,
        authorName: AUTHOR_NAME,
        authorId: AUTHOR_ID,
        authorInitials: AUTHOR_INITIALS,
        isProtected: false,
        deleteRequiresPass: true,
        publicEdit: true,
        tempTokenPhrase: Math.floor(100000 + Math.random() * 900000).toString(),
        nodes: b.nodes,
        edges: b.edges,
      });
      await syncTenantWrite("Whiteboard", "create", created, undefined, COMPANY_CODE);
      inserted++;
      console.log(`Created whiteboard: ${b.title} (${created._id}) [Nodes: ${b.nodes.length}, Edges: ${b.edges.length}]`);
    }
  }

  console.log(`\nSuccessfully seeded TaskPMS E-Commerce Plan Whiteboards: ${inserted} created, ${updated} updated!`);
  await mongoose.disconnect();
}

seed().catch((err) => {
  console.error("Seeding failed:", err);
  process.exit(1);
});
